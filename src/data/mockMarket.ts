// Generates 60 realistic candlesticks for a symbol
export function generateCandles(basePrice: number, count: number = 60, volatility: number = 0.003): Candle[] {
  const candles: Candle[] = [];
  const now = Date.now();
  let currentPrice = basePrice * (1 - count * 0.001);

  for (let i = count - 1; i >= 0; i--) {
    const time = now - i * 60 * 1000 * 5; // 5 min interval
    const change = (Math.random() - 0.48) * currentPrice * volatility;
    const open = currentPrice;
    const close = open + change;
    const high = Math.max(open, close) + Math.random() * currentPrice * (volatility * 0.7);
    const low = Math.min(open, close) - Math.random() * currentPrice * (volatility * 0.7);
    const volume = Math.floor(Math.random() * 500 + 100);

    candles.push({ time, open, high, low, close, volume });
    currentPrice = close;
  }
  return candles;
}

